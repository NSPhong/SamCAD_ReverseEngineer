namespace SamSoarII.Utility.Files.XD;

public class XDLadderDocument
{
	private string linetext;

	private string unittext;

	public string LineText
	{
		get
		{
			return linetext;
		}
		set
		{
			linetext = value;
		}
	}

	public string UnitText
	{
		get
		{
			return unittext;
		}
		set
		{
			unittext = value;
		}
	}
}
